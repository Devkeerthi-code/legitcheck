"""Write the most confident mistakes on the VALIDATION set to reports/error_analysis_cases.md.

The test set is not used here, so it stays a clean final check.
Run: python -m legitcheck.model.error_analysis
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from ..rules import run_rules
from . import data as D
from .predictor import load_model

OUT = Path(__file__).resolve().parents[2] / "reports" / "error_analysis_cases.md"
N_CASES = 8


def _snippet(row: pd.Series, limit: int = 260) -> str:
    text = " ".join(str(row["raw_text"]).split())
    return (text[:limit] + "...") if len(text) > limit else text


def _tags(row: pd.Series) -> list[str]:
    tags = []
    words = len(str(row["text"]).split())
    if words < 60:
        tags.append(f"short ({words} words)")
    if not isinstance(row["company_profile"], str) or not row["company_profile"].strip():
        tags.append("no company profile")
    if row["has_company_logo"] == 0:
        tags.append("no logo")
    if isinstance(row["location"], str) and not row["location"].startswith("US"):
        tags.append(f"location {row['location'].split(',')[0]}")
    hits = [h.id for h in run_rules(str(row["raw_text"]))]
    if hits:
        tags.append("rules: " + ", ".join(hits))
    return tags


def _case(model, row: pd.Series, score: float) -> str:
    terms = ", ".join(
        f"`{c.term}` ({c.weight:+.2f})" for c in model.contributions(row["raw_text"], k=6)
    )
    return (
        f"- **score {score:.3f}** · {row['title']} · tags: {'; '.join(_tags(row)) or 'none'}\n"
        f"  - top terms: {terms}\n"
        f"  - text: {_snippet(row)}\n"
    )


def main() -> None:
    model = load_model()
    df, _ = D.dedupe(D.load_postings())
    val = D.split(df).val
    scores = model.score_texts(val["raw_text"].tolist(), val["text"].tolist())
    y = val["fraudulent"].to_numpy()

    false_pos = np.where((y == 0) & (scores >= model.high_threshold))[0]
    false_neg = np.where((y == 1) & (scores < model.warn_threshold))[0]
    fp_order = false_pos[np.argsort(-scores[false_pos])][:N_CASES]
    fn_order = false_neg[np.argsort(scores[false_neg])][:N_CASES]

    lines = [
        "# Error analysis cases (validation set)\n",
        "Generated by `python -m legitcheck.model.error_analysis`. Dataset text is CC0 "
        "(Kaggle / EMSCAD). Commentary is in [error_analysis.md](error_analysis.md).\n",
        f"- Validation postings: {len(y)} ({int(y.sum())} fake)",
        f"- Genuine postings scored above the HIGH threshold ({model.high_threshold:.3f}): "
        f"{len(false_pos)}",
        f"- Fake postings scored below the WARN threshold ({model.warn_threshold:.3f}): "
        f"{len(false_neg)}\n",
        "## Genuine postings the model was most sure were fake\n",
        *(_case(model, val.iloc[i], scores[i]) for i in fp_order),
        "\n## Fake postings the model missed most confidently\n",
        *(_case(model, val.iloc[i], scores[i]) for i in fn_order),
    ]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {OUT} ({len(false_pos)} high-confidence FPs, {len(false_neg)} missed fakes)")


if __name__ == "__main__":
    main()
